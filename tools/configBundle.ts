// Generates src/engine/config/bundle.ts, which statically imports every config
// file for the year in config/CURRENT_YEAR. Run after changing CURRENT_YEAR or
// adding a config file: npm run config:bundle
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, configFiles, currentYear } from './lib';

const year = currentYear();
const files = configFiles(year);

const imports = files
  .map((f) => `import ${f.replace(/\.json$/, '')} from '../../../config/${year}/${f}';`)
  .join('\n');
const entries = files.map((f) => `    ${f.replace(/\.json$/, '')},`).join('\n');

const source = `// Generated by tools/configBundle.ts. Do not edit; run \`npm run config:bundle\`.
import type { RawBundle } from './load';
${imports}

export const BUNDLE: RawBundle = {
  taxYear: ${year},
  files: {
${entries}
  } as RawBundle['files'],
};
`;

writeFileSync(join(ROOT, 'src', 'engine', 'config', 'bundle.ts'), source);
console.log(`Wrote src/engine/config/bundle.ts for ${year} (${files.length} files).`);
